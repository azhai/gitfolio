// lucide renamed a few icons in v1; keep our semantic names stable.
const ICON_ALIAS = {
  'trash-2': 'trash',
  'file-code-2': 'file-code-corner',
}

// prism.js is a browser global; the language grammars attach themselves to it.
const PRISM_LANGS = [
  'markup', 'css', 'clike', 'javascript', 'jsx', 'typescript', 'tsx', 'json',
  'yaml', 'go', 'python', 'rust', 'java', 'c', 'cpp', 'csharp', 'ruby', 'php',
  'bash', 'sql', 'diff', 'ini', 'toml', 'docker', 'makefile', 'markdown',
  'nginx', 'powershell', 'vim', 'lua', 'kotlin', 'swift', 'scala', 'r',
]

function copy(from, to, label) {
  if (!existsSync(from)) {
    console.warn(`  ! missing ${label || from}`)
    return false
  }
  copyFileSync(from, to)
  return true
}

function vendorLibs() {
  mkdirSync(lib, { recursive: true })

  copy(join(nm, 'alpinejs/dist/module.esm.min.js'), join(lib, 'alpine.min.js'), 'alpinejs')
  copy(join(nm, 'marked/lib/marked.esm.js'), join(lib, 'marked.js'), 'marked')
  copy(join(nm, 'sortablejs/Sortable.min.js'), join(lib, 'sortable.min.js'), 'sortablejs')

  // Concatenate prism core + grammars into a single global script.
  const parts = [readFileSync(join(nm, 'prismjs/prism.js'), 'utf8')]
  for (const lang of PRISM_LANGS) {
    const file = join(nm, 'prismjs/components', `prism-${lang}.min.js`)
    if (!existsSync(file)) {
      console.warn(`  ! prism grammar not found: ${lang}`)
      continue
    }
    parts.push(readFileSync(file, 'utf8'))
  }
  writeFileSync(join(lib, 'prism.js'), parts.join('\n;\n'))
  console.log(`  prism: ${PRISM_LANGS.length + 1} files concatenated`)
}

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

async function vendorIcons() {
  const dir = join(nm, 'lucide/dist/esm/icons')
  if (!existsSync(dir)) {
    console.warn('  ! lucide not installed, skipping icons')
    return
  }
  mkdirSync(join(web, 'assets/js'), { recursive: true })
  const out = []
  for (const slug of ICON_SLUGS) {
    const file = join(dir, `${ICON_ALIAS[slug] || slug}.mjs`)
    if (!existsSync(file)) {
      console.warn(`  ! icon not found: ${slug}`)
      continue
    }
    const mod = await import(pathToFileURL(file))
    const nodes = mod.default || []
    const body = nodes
      .map(([tag, attrs]) => {
        const a = Object.entries(attrs || {})
          .map(([k, v]) => ` ${k}="${esc(v)}"`)
          .join('')
        return `<${tag}${a}/>`
      })
      .join('')
    out.push(`  ${JSON.stringify(slug)}: ${JSON.stringify(body)},`)
  }
  const header = [
    '// Generated by scripts/vendor.mjs from lucide. Do not edit by hand.',
    '// Each entry is the inner markup of a 24x24 stroke icon.',
    'export const ICONS = {',
    ...out,
    '}',
    '',
  ].join('\n')
  writeFileSync(join(web, 'assets/js/icons.js'), header)
  console.log(`  icons: ${out.length} generated`)
}

function pathToFileURL(p) {
  return new URL('file://' + p)
}

console.log('vendoring frontend libraries ->', lib)
vendorLibs()
await vendorIcons()
console.log('done')
