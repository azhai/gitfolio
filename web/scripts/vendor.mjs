// Copies the runtime libraries we need from node_modules into assets/lib,
// so the site runs as plain static files with no bundler in the loop.
//
// Run it after changing a dependency:  pnpm run vendor
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const web = join(here, '..')
const nm = join(web, 'node_modules')
const lib = join(web, 'assets', 'lib')

